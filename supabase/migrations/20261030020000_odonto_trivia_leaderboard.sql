-- OdontoUdeC: trivia segura con puntuación y ranking persistentes.
-- Ejecutar en el SQL Editor del proyecto Supabase conectado a OdontoUdeC.

create table if not exists public.trivia_questions (
  id bigint generated by default as identity primary key,
  category text not null,
  difficulty text not null check (difficulty in ('Básica','Intermedia','Avanzada')),
  question text not null,
  options jsonb not null check (jsonb_typeof(options) = 'array' and jsonb_array_length(options) = 4),
  correct_index smallint not null check (correct_index between 0 and 3),
  explanation text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.trivia_attempts (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  score integer not null check (score between 0 and 100),
  total_questions smallint not null default 10 check (total_questions = 10),
  correct_answers smallint not null check (correct_answers between 0 and 10),
  category text not null default 'Mixta',
  created_at timestamptz not null default now()
);

create index if not exists trivia_attempts_user_created_idx
  on public.trivia_attempts(user_id, created_at desc);
create index if not exists trivia_attempts_score_idx
  on public.trivia_attempts(score desc, created_at asc);

alter table public.trivia_questions enable row level security;
alter table public.trivia_attempts enable row level security;
revoke all on public.trivia_questions from public, anon, authenticated;
revoke all on public.trivia_attempts from public, anon, authenticated;
grant usage, select on sequence public.trivia_questions_id_seq to service_role;
grant usage, select on sequence public.trivia_attempts_id_seq to service_role;

-- Entrega diez preguntas sin revelar sus respuestas correctas.
create or replace function public.get_trivia_round()
returns jsonb
language sql
security definer
set search_path = public
as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', q.id,
    'category', q.category,
    'difficulty', q.difficulty,
    'question', q.question,
    'options', q.options
  )), '[]'::jsonb)
  from (
    select id, category, difficulty, question, options
    from public.trivia_questions
    where is_active
    order by random()
    limit 10
  ) q;
$$;

-- Corrige y puntúa en el servidor; el navegador nunca decide la nota.
create or replace function public.submit_trivia_attempt(p_answers jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  answer_item jsonb;
  question_row public.trivia_questions%rowtype;
  answer_count integer := 0;
  correct_count integer := 0;
  result_details jsonb := '[]'::jsonb;
  selected_index integer;
  attempt_id bigint;
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión para guardar tu puntuación.';
  end if;
  if p_answers is null or jsonb_typeof(p_answers) is distinct from 'array' then
    raise exception 'Formato de ronda inválido.';
  end if;
  if jsonb_array_length(p_answers) <> 10 then
    raise exception 'La ronda debe contener exactamente diez respuestas.';
  end if;

  for answer_item in select value from jsonb_array_elements(p_answers)
  loop
    answer_count := answer_count + 1;
    if not (answer_item ? 'id' and answer_item ? 'selected_index') then
      raise exception 'Formato de respuesta inválido.';
    end if;
    selected_index := (answer_item->>'selected_index')::integer;
    if selected_index is null or selected_index < 0 or selected_index > 3 then
      raise exception 'Opción inválida.';
    end if;

    select * into question_row
    from public.trivia_questions
    where id = (answer_item->>'id')::bigint and is_active;

    if not found then
      raise exception 'Una pregunta ya no está disponible.';
    end if;

    if exists (
      select 1 from jsonb_array_elements(p_answers) as items(value)
      where value->>'id' = answer_item->>'id'
      having count(*) > 1
    ) then
      raise exception 'No se permiten respuestas duplicadas.';
    end if;

    if selected_index = question_row.correct_index then
      correct_count := correct_count + 1;
    end if;

    result_details := result_details || jsonb_build_array(jsonb_build_object(
      'id', question_row.id,
      'correct', selected_index = question_row.correct_index,
      'correct_index', question_row.correct_index,
      'explanation', question_row.explanation
    ));
  end loop;

  insert into public.trivia_attempts(user_id, score, total_questions, correct_answers)
  values (auth.uid(), correct_count * 10, 10, correct_count)
  returning id into attempt_id;

  return jsonb_build_object(
    'attempt_id', attempt_id,
    'score', correct_count * 10,
    'correct_answers', correct_count,
    'total_questions', 10,
    'details', result_details
  );
end;
$$;

create or replace function public.get_trivia_leaderboard(limit_count integer default 20)
returns table (
  rank_position bigint,
  user_id uuid,
  display_name text,
  username text,
  total_points bigint,
  rounds_played bigint,
  best_score integer
)
language sql
security definer
set search_path = public
as $$
  select
    row_number() over (order by sum(a.score) desc, max(a.score) desc, min(a.created_at) asc) as rank_position,
    p.id as user_id,
    coalesce(nullif(p.display_name, ''), 'Estudiante') as display_name,
    p.username,
    sum(a.score)::bigint as total_points,
    count(*)::bigint as rounds_played,
    max(a.score)::integer as best_score
  from public.trivia_attempts a
  join public.profiles p on p.id = a.user_id
  group by p.id, p.display_name, p.username
  order by sum(a.score) desc, max(a.score) desc, min(a.created_at) asc
  limit greatest(1, least(coalesce(limit_count, 20), 100));
$$;

revoke all on function public.get_trivia_round() from public, anon;
revoke all on function public.submit_trivia_attempt(jsonb) from public, anon;
revoke all on function public.get_trivia_leaderboard(integer) from public, anon;
grant execute on function public.get_trivia_round() to authenticated;
grant execute on function public.submit_trivia_attempt(jsonb) to authenticated;
grant execute on function public.get_trivia_leaderboard(integer) to authenticated;

