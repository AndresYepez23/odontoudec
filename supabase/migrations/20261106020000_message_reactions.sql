-- Reacciones para publicaciones y mensajes de OdontoUdeC.
begin;
alter table public.post_reactions drop constraint if exists post_reactions_reaction_check;
alter table public.post_reactions add constraint post_reactions_reaction_check
  check (reaction in ('apoyo','me_encanta','idea','gracias','divertido','sorprendido'));

create table if not exists public.chat_message_reactions (
  id bigint generated by default as identity primary key,
  chat_message_id bigint references public.chat_messages(id) on delete cascade,
  private_message_id uuid references public.private_messages(id) on delete cascade,
  group_message_id uuid references public.study_group_messages(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  reaction text not null check (reaction in ('apoyo','me_encanta','idea','gracias','divertido','sorprendido')),
  created_at timestamptz not null default now(),
  constraint chat_message_reactions_one_target check (
    num_nonnulls(chat_message_id, private_message_id, group_message_id) = 1
  )
);
create unique index if not exists chat_message_reactions_community_user_uidx
  on public.chat_message_reactions(chat_message_id,user_id) where chat_message_id is not null;
create unique index if not exists chat_message_reactions_private_user_uidx
  on public.chat_message_reactions(private_message_id,user_id) where private_message_id is not null;
create unique index if not exists chat_message_reactions_group_user_uidx
  on public.chat_message_reactions(group_message_id,user_id) where group_message_id is not null;

alter table public.chat_message_reactions enable row level security;
drop policy if exists "Participants can read message reactions" on public.chat_message_reactions;
create policy "Participants can read message reactions"
on public.chat_message_reactions for select to authenticated using (
  (chat_message_id is not null and exists (select 1 from public.chat_messages m where m.id=chat_message_id))
  or (private_message_id is not null and exists (
    select 1 from public.private_messages pm
    join public.private_conversations pc on pc.id=pm.conversation_id
    where pm.id=private_message_id and auth.uid() in (pc.user_one,pc.user_two)
  ))
  or (group_message_id is not null and exists (
    select 1 from public.study_group_messages gm
    join public.study_group_members gmbr on gmbr.group_id=gm.group_id
    where gm.id=group_message_id and gmbr.user_id=auth.uid()
  ))
);
drop policy if exists "Participants can add own message reactions" on public.chat_message_reactions;
create policy "Participants can add own message reactions"
on public.chat_message_reactions for insert to authenticated with check (
  user_id=auth.uid() and (
    (chat_message_id is not null and exists (select 1 from public.chat_messages m where m.id=chat_message_id))
    or (private_message_id is not null and exists (
      select 1 from public.private_messages pm
      join public.private_conversations pc on pc.id=pm.conversation_id
      where pm.id=private_message_id and auth.uid() in (pc.user_one,pc.user_two)
    ))
    or (group_message_id is not null and exists (
      select 1 from public.study_group_messages gm
      join public.study_group_members gmbr on gmbr.group_id=gm.group_id
      where gm.id=group_message_id and gmbr.user_id=auth.uid()
    ))
  )
);
drop policy if exists "Users delete own message reactions" on public.chat_message_reactions;
create policy "Users delete own message reactions"
on public.chat_message_reactions for delete to authenticated using (user_id=auth.uid());
grant select,insert,delete on public.chat_message_reactions to authenticated;
grant usage,select on sequence public.chat_message_reactions_id_seq to authenticated;
commit;